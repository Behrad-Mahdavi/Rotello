export function generateDefaultChecklistItems(): TemplateChecklistItem[] {
  const result: TemplateChecklistItem[] = []
  let sortOrder = 1

  for (const cat of EVENT_CATEGORIES) {
    for (const item of cat.items) {
      result.push({
        category_key: cat.key,
        category_title: cat.title,
        title: item.title,
        sort_order: sortOrder++,
      })
    }
  }

  return result
}
